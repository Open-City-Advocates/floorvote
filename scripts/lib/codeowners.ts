// .github/CODEOWNERS, rendered from the provider registry.
//
// Used by scripts/gen-codeowners.ts (writes the file) and by the drift test
// beside this file (fails CI when the committed file no longer matches what
// the providers declare). The pull request workflow that mentions maintainers
// (.github/workflows/provider-maintainers.yml) reads the committed file.

import type { Provider } from '../../central/src/providers'
import { STATES } from './state-coverage'

export const CODEOWNERS_PATH = '.github/CODEOWNERS'

/** Owns everything the lines below don't name. */
export const PROJECT_OWNER = 'wtadler'

/** The provider interface, registry, SDK, and the lint rule and check that hold the boundary. */
export const CORE_BOUNDARY_PATHS: readonly string[] = [
  '/central/src/providers/',
  '/central/eslint.config.mjs',
  '/central/eslint-provider-boundary.mjs',
  '/central/scripts/check-provider-boundary.mjs',
]

const PROVIDERS_ROOT = '/central/src/providers/'
const PROVIDER_TESTS_ROOT = '/central/test/providers/'

/**
 * The file's text. `hasTestDir` says whether `central/test/providers/<id>/`
 * exists, since a provider's test directory is owned only when it does.
 * Providers are listed by id so the order doesn't depend on the registry's.
 */
export function renderCodeowners(
  providers: readonly Pick<Provider, 'id' | 'displayName' | 'states' | 'coverage'>[],
  hasTestDir: (id: string) => boolean,
): string {
  const starOwners = [PROJECT_OWNER]
  const lines: [path: string, owners: string[], comment?: string][] = [
    ['*', starOwners],
    ...CORE_BOUNDARY_PATHS.map((p): [string, string[]] => [p, [PROJECT_OWNER]]),
  ]
  for (const p of [...providers].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))) {
    // The owners of `*` stay owners here, since a later line replaces the earlier ones.
    const owners = [...new Set([...p.coverage.maintainers, ...starOwners])]
    const covers = p.states ? p.states.map(code => STATES[code]).join(', ') : 'all states, the District of Columbia, and Congress'
    lines.push([`${PROVIDERS_ROOT}${p.id}/`, owners, `${p.id}: ${p.displayName} (${covers})`])
    if (hasTestDir(p.id)) lines.push([`${PROVIDER_TESTS_ROOT}${p.id}/`, owners])
  }
  const width = Math.max(...lines.map(([path]) => path.length))
  const body = lines.flatMap(([path, owners, comment]) => [
    ...(comment ? [`# ${comment}`] : []),
    `${path.padEnd(width)} ${owners.map(o => `@${o}`).join(' ')}`,
  ])

  return `# Generated by scripts/gen-codeowners.ts from the providers in central/src/providers.
# Do not edit by hand: change a provider's \`coverage.maintainers\` and run
# \`npm run gen:codeowners\`. CI fails when this file is out of date.
#
# The project owner owns everything. The provider interface, registry, SDK, and
# the lint rule and check that hold the boundary stay with the project owner.
# Each provider's directory and tests then name that provider's maintainers. A
# later line wins for the paths it matches, so each provider's lines sit below
# the providers/ line. The comment above each provider's lines names it.

${body.join('\n')}
`
}
