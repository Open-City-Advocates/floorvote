const CAPABILITY_LABELS: Readonly<Record<keyof ListedCapabilities, string>> = {
  bills: 'Bills',
  memberVotes: 'Member votes',
  bodyEvents: 'Hearings without bills',
  billText: 'Bill text',
  extras: 'Extras',
  deadlines: 'Deadlines',
}

const handleLink = (handle: string) => `[@${handle}](https://github.com/${handle})`

/** The providers available for a state: its direct providers, then LegiScan, which serves every state. */
function providersFor(providers: readonly Provider[], state: string): Provider[] {
  const direct = providers.filter(p => p.states?.includes(state))
  const everywhere = providers.filter(p => !p.states)
  return [...direct, ...everywhere]
}

/**
 * The page's Markdown. `capabilities` is each provider's `listedCapabilities`,
 * passed in so this module needs nothing from central but types.
 */
export function renderStateCoverage(
  providers: readonly Provider[],
  capabilities: (provider: Provider) => ListedCapabilities,
): string {
  const legend = (Object.keys(CAPABILITY_LABELS) as (keyof ListedCapabilities)[])
    .map(k => CAPABILITY_LABELS[k])
  const rows = Object.entries(STATES)
    .sort(([, a], [, b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([code, name]) => {
      const available = providersFor(providers, code)
      const cell = (f: (p: Provider) => string) => available.map(f).join('<br>')
      const supplies = (p: Provider) => {
        const caps = capabilities(p)
        return (Object.keys(CAPABILITY_LABELS) as (keyof ListedCapabilities)[])
          .filter(k => caps[k])
          .map((k, i) => (i === 0 ? CAPABILITY_LABELS[k] : CAPABILITY_LABELS[k].toLowerCase()))
          .join(', ')
      }
      return `| ${name} (${code}) | ${[
        cell(p => p.displayName),
        cell(p => p.coverage.status),
        cell(p => p.coverage.maintainers.map(handleLink).join(', ')),
        cell(supplies),
      ].join(' | ')} |`
    })

  return `---
description: "Which data providers exist for each state, what each supplies, how mature it is, and who maintains it."
---

<!-- Generated by scripts/gen-state-coverage.ts from the providers in central/src/providers. Do not edit by hand: change the provider's declaration and run \`npm run gen:state-coverage\`. -->

# State coverage

This page lists the data providers that exist for each state. It does not say which provider a given deployment uses. That is set by the deployment's own state ownership table, and every state starts on LegiScan until an operator opts in to a direct provider.

[LegiScan](https://legiscan.com) supplies every state, the District of Columbia, and Congress. Some legislatures also publish their own data, and a direct provider reads it from the source. Direct providers are opt-in and start out experimental. A deployment that never opts in keeps using LegiScan.

This page is generated from what each provider declares in code, so it can't drift from the providers themselves. Maintainers are the people CODEOWNERS asks to review changes to the provider.

## What the columns mean

- **Status:** \`stable\` providers have run in production through a legislative session. \`experimental\` providers work but are newer, so expect rough edges.
- **Supplies:** ${legend.map(l => l.toLowerCase()).join(', ')}. Member votes are how each legislator voted. Hearings without bills are the legislature's own calendar, including meetings with no bill on the agenda. Extras are fields only that provider publishes, shown on the bill page. Deadlines are dates the law sets for a bill's next step.

## Providers by state

When a state has more than one provider, each column lists them in the same order.

| State | Providers | Status | Maintainers | Supplies |
| --- | --- | --- | --- | --- |
${rows.join('\n')}
`
}

/**
 * Problems with CODEOWNERS: each registered provider's directory must have a
 * line naming exactly the maintainers the provider declares. A directory with
 * a line but no registered provider (a template, say) is not checked.
 */
export function checkCodeowners(codeowners: string, providers: readonly Provider[]): string[] {
  const owners = new Map<string, string[]>()
  for (const raw of codeowners.split('\n')) {
    const line = raw.replace(/#.*/, '').trim()
    if (!line) continue
    const [path, ...who] = line.split(/\s+/)
    owners.set(path, who) // a later line wins, as on GitHub
  }
  const problems: string[] = []
  for (const p of providers) {
    const dir = `/central/src/providers/${p.id}/`
    const declared = p.coverage.maintainers.map(h => `@${h}`)
    const actual = owners.get(dir)
    if (!actual) problems.push(`${CODEOWNERS_PATH} has no line for ${dir}. Add: ${dir} ${declared.join(' ')}`)
    else if ([...actual].sort().join(' ') !== [...declared].sort().join(' ')) {
      problems.push(`${CODEOWNERS_PATH} names ${actual.join(' ')} for ${dir}, but ${p.id} declares ${declared.join(' ')}`)
    }
  }
  return problems
}
