import { existsSync, readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'
import { PROVIDERS } from '../../central/src/providers'
import { CODEOWNERS_PATH, renderCodeowners } from './codeowners'

const ROOT = resolve(__dirname, '../..')
const read = (path: string) => readFileSync(resolve(ROOT, path), 'utf8')

const provider = (id: string, maintainers: string[]): Parameters<typeof renderCodeowners>[0][number] => ({
  id,
  coverage: { maintainers, status: 'experimental', memberVotes: false, billText: false },
})
const ownerLines = (text: string) => text.split('\n').filter(l => l && !l.startsWith('#')).map(l => l.split(/\s+/))

describe('CODEOWNERS', () => {
  it('matches what the providers declare (run `npm run gen:codeowners`)', () => {
    const generated = renderCodeowners(PROVIDERS, id => existsSync(resolve(ROOT, 'central/test/providers', id)))
    expect(read(CODEOWNERS_PATH)).toBe(generated)
  })

  it('names, for each registered provider, exactly its declared maintainers', () => {
    const lines = new Map(ownerLines(read(CODEOWNERS_PATH)).map(([path, ...owners]) => [path, owners]))
    for (const p of PROVIDERS) {
      expect(lines.get(`/central/src/providers/${p.id}/`), p.id).toEqual(p.coverage.maintainers.map(h => `@${h}`))
    }
  })
})

describe('renderCodeowners', () => {
  const providers = [provider('mga', ['jo', 'wtadler']), provider('lims', ['wtadler']), provider('lis', ['jo'])]
  const text = renderCodeowners(providers, id => id !== 'lis')
  const lines = ownerLines(text)

  it('starts with the project owner on everything, then the core boundary', () => {
    expect(lines.slice(0, 5)).toEqual([
      ['*', '@wtadler'],
      ['/central/src/providers/', '@wtadler'],
      ['/central/eslint.config.mjs', '@wtadler'],
      ['/central/eslint-provider-boundary.mjs', '@wtadler'],
      ['/central/scripts/check-provider-boundary.mjs', '@wtadler'],
    ])
  })

  it('lists providers by id, each after the providers/ line, with its tests when they exist', () => {
    expect(lines.slice(5)).toEqual([
      ['/central/src/providers/lims/', '@wtadler'],
      ['/central/test/providers/lims/', '@wtadler'],
      ['/central/src/providers/lis/', '@jo'],
      ['/central/src/providers/mga/', '@jo', '@wtadler'],
      ['/central/test/providers/mga/', '@jo', '@wtadler'],
    ])
  })

  it('says it is generated, and from where', () => {
    expect(text.split('\n')[0]).toBe('# Generated by scripts/gen-codeowners.ts from the providers in central/src/providers.')
  })

  it('does not depend on the order the registry lists providers in', () => {
    const exists = () => true
    expect(renderCodeowners([...providers].reverse(), exists)).toBe(renderCodeowners(providers, exists))
  })
})

// The workflow's script is read from the YAML and run against a fake GitHub
// client, so these tests exercise the code that runs in Actions.
describe('provider-maintainers workflow', () => {
  const workflow = read('.github/workflows/provider-maintainers.yml')
  const script = (() => {
    const lines = workflow.split('\n')
    const start = lines.findIndex(l => l.trim() === 'script: |')
    const indent = lines[start + 1].match(/^ */)![0].length
    return lines.slice(start + 1).map(l => l.slice(indent)).join('\n')
  })()
  const AsyncFunction = Object.getPrototypeOf(async () => {}).constructor as new (...args: string[]) => (...args: unknown[]) => Promise<void>
  const run = new AsyncFunction('github', 'context', script)

  const CODEOWNERS = renderCodeowners(
    [provider('lims', ['anotherpanacea-eng', 'wtadler']), provider('lis', ['anotherpanacea-eng', 'wtadler']), provider('legiscan', ['wtadler'])],
    () => true,
  )

  /** A fake client for a pull request by `author` that changes `files`, with `comments` already on it. */
  function fake(author: string, files: { filename: string; previous_filename?: string }[], comments: { id: number; user: { login: string }; body: string }[] = []) {
    const calls: { kind: string; args: Record<string, unknown> }[] = []
    const github = {
      paginate: async (fn: (a: unknown) => unknown) => (fn === github.rest.pulls.listFiles ? files : comments),
      rest: {
        repos: { getContent: async () => ({ data: { content: Buffer.from(CODEOWNERS).toString('base64') } }) },
        pulls: { listFiles: () => {} },
        issues: {
          listComments: () => {},
          createComment: async (args: Record<string, unknown>) => { calls.push({ kind: 'create', args }) },
          updateComment: async (args: Record<string, unknown>) => { calls.push({ kind: 'update', args }) },
        },
      },
    }
    const context = {
      repo: { owner: 'floorvote', repo: 'floorvote' },
      payload: { pull_request: { number: 7, user: { login: author }, base: { ref: 'main' } } },
    }
    return { github, context, calls }
  }
  const go = async (...args: Parameters<typeof fake>) => {
    const f = fake(...args)
    await run(f.github, f.context)
    return f.calls
  }

  it('mentions a provider\'s maintainers on a pull request that changes it', async () => {
    const calls = await go('someone', [{ filename: 'central/src/providers/lis/map.ts' }])
    expect(calls).toHaveLength(1)
    expect(calls[0].kind).toBe('create')
    expect(calls[0].args.body).toBe(
      '<!-- provider-maintainers -->\n@anotherpanacea-eng, this pull request changes the `lis` provider, which you maintain.',
    )
  })

  it('never mentions a project maintainer', async () => {
    const calls = await go('someone', [{ filename: 'central/src/providers/legiscan/client.ts' }, { filename: 'central/src/providers/lims/map.ts' }])
    expect(calls[0].args.body).toBe('<!-- provider-maintainers -->\n@anotherpanacea-eng, this pull request changes the `lims` provider, which you maintain.')
    expect(String(calls[0].args.body)).not.toContain('wtadler')
  })

  it('posts nothing on a project maintainer\'s pull request, in any case', async () => {
    expect(await go('WTadler', [{ filename: 'central/src/providers/lis/map.ts' }])).toEqual([])
  })

  it('posts nothing on a provider maintainer\'s own provider', async () => {
    expect(await go('AnotherPanacea-Eng', [{ filename: 'central/src/providers/lis/map.ts' }])).toEqual([])
  })

  it('posts nothing when only project maintainers maintain the provider', async () => {
    expect(await go('someone', [{ filename: 'central/src/providers/legiscan/client.ts' }])).toEqual([])
  })

  it('counts a provider\'s tests and renames, once, one line per provider in id order', async () => {
    const calls = await go('someone', [
      { filename: 'central/test/providers/lims/map.test.ts' },
      { filename: 'central/src/providers/lis/new.ts', previous_filename: 'central/src/providers/lims/old.ts' },
      { filename: 'central/src/providers/lims/map.ts' },
    ])
    expect(calls).toHaveLength(1)
    expect(calls[0].args.body).toBe(
      '<!-- provider-maintainers -->\n'
      + '@anotherpanacea-eng, this pull request changes the `lims` provider, which you maintain.\n\n'
      + '@anotherpanacea-eng, this pull request changes the `lis` provider, which you maintain.',
    )
  })

  it('ignores the registry, the SDK, other directories, and directories no provider owns', async () => {
    expect(await go('someone', [
      { filename: 'central/src/providers/index.ts' },
      { filename: 'central/src/providers/sdk.ts' },
      { filename: 'central/src/providers/template/index.ts' },
      { filename: 'central/test/cron/lims-provider.test.ts' },
      { filename: 'api/src/providers/lims/x.ts' },
    ])).toEqual([])
  })

  it('updates the one marker comment instead of adding another, and only when it changes', async () => {
    const files = [{ filename: 'central/src/providers/lis/map.ts' }]
    const stale = { id: 99, user: { login: 'github-actions[bot]' }, body: '<!-- provider-maintainers -->\nold' }
    const calls = await go('someone', files, [stale])
    expect(calls.map(c => c.kind)).toEqual(['update'])
    expect(calls[0].args.comment_id).toBe(99)

    const current = { ...stale, body: (await go('someone', files))[0].args.body as string }
    expect(await go('someone', files, [current])).toEqual([])
  })

  it('ignores a marker comment someone else wrote', async () => {
    const spoof = { id: 5, user: { login: 'someone' }, body: '<!-- provider-maintainers -->\nhi' }
    const calls = await go('someone', [{ filename: 'central/src/providers/lis/map.ts' }], [spoof])
    expect(calls.map(c => c.kind)).toEqual(['create'])
  })

  it('never checks out or runs the pull request\'s code, and runs on ready pull requests only', () => {
    expect(workflow).toContain('pull_request_target:')
    expect(workflow).not.toMatch(/uses:\s*actions\/checkout/)
    expect(workflow).not.toMatch(/^\s+run:/m)
    expect(workflow).toContain('types: [opened, synchronize, reopened, ready_for_review]')
    expect(workflow).toContain('github.event.pull_request.draft == false')
    expect(workflow).toMatch(/permissions:\n {2}contents: read\n {2}pull-requests: write\n/)
    expect(workflow).toMatch(/uses: actions\/github-script@[0-9a-f]{40} # v/)
  })
})
